// Writes supabase/migrations/0003_topics.sql from src/lib/domain/topics.ts.
// Run: npm run gen:topics   (a unit test fails if the file is out of date)
import { writeFileSync } from "node:fs";
import { TOPICS } from "../src/lib/domain/topics";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

export function topicsSql() {
  const rows = TOPICS.map(
    (t) => `  (${q(t.id)}, ${q(t.parentId)}, ${q(t.name)}, ${q(t.description ?? null)}, ${q(t.sensitivity)}, ${arr(t.keywords)})`,
  );
  return `-- GENERATED by scripts/gen-topics-sql.ts — edit src/lib/domain/topics.ts instead.
insert into public.topics (id, parent_id, name, description, sensitivity, keywords) values
${rows.join(",\n")}
on conflict (id) do update set parent_id = excluded.parent_id, name = excluded.name,
  description = excluded.description, sensitivity = excluded.sensitivity, keywords = excluded.keywords;
`;
}

if (process.argv[1]?.endsWith("gen-topics-sql.ts")) {
  writeFileSync(new URL("../supabase/migrations/0003_topics.sql", import.meta.url), topicsSql());
  console.log("wrote supabase/migrations/0003_topics.sql");
}
